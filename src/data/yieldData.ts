// ── Wachstums-Detail-Typen ───────────────────────────────────────────────────
// Eine Farb-/Reifephase, durch die die Frucht/Knolle/Blatt geht.
// `atFraction` ist 0 = Anlage sichtbar, 1 = Vollreife/Ende Erntefenster.
export interface ColorStage {
  label: string;             // z.B. 'grün', 'orange', 'tiefrot'
  hex: string;               // Darstellungsfarbe (für UI-Punkte)
  atFraction: number;        // 0..1 entlang Frucht-Entwicklung
  description?: string;      // optionaler Begleittext
}

// Eine konkrete physische Dimension der reifen Frucht / des Ernteguts
// (nicht der ganzen Pflanze - das ist heightCm/spreadCm).
export interface FruitSize {
  lengthCm?: number;         // Länge bei länglichen Früchten
  diameterCm?: number;       // Durchmesser bei runden Früchten
  weightG?: number;          // typisches Stück-Gewicht in Gramm
  note?: string;             // z.B. 'Erntegröße - größer = überreif'
}

export interface YieldEntry {
  plantId: string;
  name: string;
  category: 'gemuese' | 'kraeuter' | 'obst' | 'salat';
  // Anbau
  spacingCm: number;         // Pflanzabstand in cm
  rowSpacingCm: number;      // Reihenabstand in cm
  plantsPerM2: number;       // errechnete Pflanzen pro m²
  // Ertrag
  yieldKgPerM2Low: number;   // kg/m² untere Grenze (Anfänger)
  yieldKgPerM2High: number;  // kg/m² obere Grenze (erfahren)
  yieldPerPlantKg?: number;  // kg pro Einzelpflanze (wenn sinnvoller)
  // Zeit (Wochen ab Aussaat/Pflanzung)
  weeksToHarvest: number;     // Wochen bis erste vollreife Ernte (für Abwärtskompatibilität = fullRipeWeeks)
  weeksToFirstFruit?: number; // erste kleine Früchte/Anlagen sichtbar (vor Vollreife). Bei Blattgemüse: Pflück-/Baby-Leaf-Start.
  weeksToFullRipe?: number;   // tatsächlich erntereif/voll ausgereift (Vollernte)
  harvestWindowWeeks: number; // Wochen Erntezeitraum
  successionalSowings: number; // empfohlene Staffelaussaaten pro Saison
  // Kalorien & Nährwert
  kcalPer100g: number;
  // Glashaus-Bonus
  glashausYieldMultiplier?: number; // z.B. 1.5 = 50% mehr im Glashaus
  // Lagerung
  storageMonths: number;     // Monate lagerfähig (0 = nur frisch)
  storageMethod: string;
  // Visualisierung
  heightCm: number;          // Endhöhe der Pflanze
  spreadCm: number;          // Breite/Durchmesser der ausgewachsenen Pflanze
  growthForm: 'upright' | 'bushy' | 'spreading' | 'climbing' | 'rosette' | 'root';
  color: string;             // Darstellungsfarbe
  // Detail-Visualisierung: Reife-Phasen + Endgröße der Frucht
  colorStages?: ColorStage[];  // Farb-/Reifephasen, geordnet von Anlage -> Vollreife
  fruitSize?: FruitSize;       // physische Größe der reifen Einzelfrucht
  // Zeitfenster (Monat 1-12)
  sowIndoorMonth?: number;   // Vorkultur ab Monat
  sowOutdoorMonth: number;   // Freiland-Aussaat/Pflanzung ab Monat
  harvestStartMonth: number; // Ernte ab Monat
  harvestEndMonth: number;   // Ernte bis Monat
  needsSupport?: boolean;    // braucht Stab/Rankhilfe
}

// Helper: liefert Vollreife- und Erstfrucht-Wochen, mit Fallback auf weeksToHarvest.
export function getRipeningTimeline(e: YieldEntry): { firstFruitWeeks: number; fullRipeWeeks: number } {
  const fullRipe = e.weeksToFullRipe ?? e.weeksToHarvest;
  // Wenn nicht angegeben: Heuristik - erste Früchte bei ~70% des Vollreife-Zeitpunkts
  // (für Fruchtgemüse plausibel; für Blattgemüse Anpassung über expliziten Wert).
  const firstFruit = e.weeksToFirstFruit ?? Math.max(1, Math.round(fullRipe * 0.7));
  return { firstFruitWeeks: firstFruit, fullRipeWeeks: fullRipe };
}

